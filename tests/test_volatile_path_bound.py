"""kit#137: the volatile semantic check's path bound is a cost bound of 1024 paths."""

import sys
import unittest
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import volatile_semantics as semantics


SYMBOL = "g_control_flags_03000940"
DECLARATION = ("extern struct { u16 display; u8 unknown_02[0x3A]; volatile u8 unknown_3C : 8; "
               "volatile u8 unknown_3D : 8; } " + SYMBOL + ";")
PREPROCESSED = "void func_08028C34(int);\n"


def branches(count, load=True):
    """`count` independent tests of the argument, then `sym.unknown_3C = 1`: 2**count paths"""
    body = []
    for n in range(1, count + 1):
        body += [f"cmp\tr0, #{n}", f"beq\t.L{100 + n}", f"add\tr1, r1, #{n}", f".L{100 + n}:"]
    body += ["ldr\tr2, .L3", "add\tr2, r2, #60"] + (["ldrb\tr3, [r2]"] if load else []) + \
        ["mov\tr3, #1", "strb\tr3, [r2]", "bx\tlr"]
    name = "func_08028C34"
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{name}\n\t.type\t {name},function\n\t.thumb_func\n{name}:\n" +
            "".join(f"{line}\n" if line.endswith(":") else f"\t{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n"
            f"\t.size\t {name},.Lfe1-{name}\n")


def compare(count):
    real = branches(count)
    return semantics.compare(real, branches(count, load=False), PREPROCESSED, SYMBOL, DECLARATION,
                             real.replace("#60", "#61"))


class PathBoundTests(unittest.TestCase):
    def test_the_bound_is_1024_paths(self):
        self.assertEqual(semantics.MAX_PATHS, 1024)
        self.assertEqual(semantics.MAX_DECISIONS, 32)

    def test_more_than_256_paths_are_checked_in_full(self):
        (result,) = compare(9)
        self.assertEqual(result[:2], ("func_08028C34", 512))
        # every one of them still gets the full rules
        real = branches(9).replace("beq\t.L109", "beq\t.L200").replace(
            "bx\tlr", "bx\tlr\n.L200:\n\tldr\tr2, .L3\n\tmov\tr3, #2\n\tstrb\tr3, [r2, #60]\n\tbx\tlr")
        with self.assertRaises(semantics.SemanticError) as caught:
            semantics._compare_compiles(real, real, PREPROCESSED, SYMBOL, DECLARATION)
        self.assertIn("without the read-modify-write load", str(caught.exception))

    def test_more_than_1024_paths_are_refused(self):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(11)
        self.assertIn("has more than 1024 paths; the semantic check is bounded", str(caught.exception))


if __name__ == "__main__":
    unittest.main()
