SYMBOL = "g_control_flags_03000940"
DECLARATION = ("extern struct { u16 display; u8 unknown_02[0x3A]; volatile u8 unknown_3C : 8; "
               "volatile u8 unknown_3D : 8; } " + SYMBOL + ";")
PREPROCESSED = "void func_08028C34(void);\nextern void func_0802A2C0(int);\n"
# a mixed declaration: two volatile halfwords and two volatile bytes
DECLARATION16 = ("extern struct { u16 display; volatile u16 bg0cnt : 16; volatile u16 bg1cnt : 16; "
                 "u8 unknown_06[0x34]; volatile u8 unknown_3A : 8; volatile u8 unknown_3B : 8; } "
                 + SYMBOL + ";")


def assembly(*body, name="func_08028C34"):
    """agbcc-shaped output for one Thumb function with a one-word pool"""
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{name}\n\t.type\t {name},function\n\t.thumb_func\n{name}:\n" +
            "".join(f"\t{line}\n" if not line.endswith(":") else f"{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n"
            f"\t.size\t {name},.Lfe1-{name}\n")


def compare(real, stripped, preprocessed=PREPROCESSED):
    """the stripped-compile rules alone (the perturbation has its own tests)"""
    return semantics._compare_compiles(real, stripped, preprocessed, SYMBOL, DECLARATION)


class SemanticDiffTests(unittest.TestCase):
    def refused(self, real, stripped, reason):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real, stripped)
        self.assertIn(reason, str(caught.exception))

    def test_layout_of_the_pinned_declaration(self):
        self.assertEqual(semantics.object_layout(DECLARATION), (0x3E, {0x3C, 0x3D}))
        # the shipped entry: halfwords +0x02..+0x39 (BG0CNT..BG3Y_H) and the
        # bytes of +0x3A..+0x4E that the ROM stores (not MOSAIC's high
        # byte, the unused 0x0400004E or BLDY's high byte)
        shipped = plausible.volatile_allow_entries()[0]["declaration"]
        self.assertEqual(semantics.pinned_members(shipped),
                         (0x50, {**{offset: 2 for offset in range(0x02, 0x3A, 2)},
                                 **{offset: 1 for offset in list(range(0x3A, 0x47)) + list(range(0x4A, 0x4F))}}))
        self.assertEqual(semantics.pinned_members(DECLARATION16),
                         (0x3C, {0x02: 2, 0x04: 2, 0x3A: 1, 0x3B: 1}))
        for broken in (DECLARATION.replace(": 8", ": 4"), DECLARATION.replace("u16", "float"),
                       DECLARATION.replace("volatile u8 unknown_3D : 8", "volatile u32 unknown_3D : 32"),
                       DECLARATION16.replace("volatile u16 bg1cnt : 16", "volatile u16 bg1cnt : 8"),
                       DECLARATION16.replace("volatile u16 bg1cnt : 16", "volatile u16 bg1cnt[1]"),
                       DECLARATION16.replace("volatile u16 bg1cnt : 16", "volatile u16 bg1cnt : 016"),
                       DECLARATION16.replace("[0x34]", "[064]")):
            with self.subTest(declaration=broken), self.assertRaises(semantics.SemanticError):
                semantics.object_layout(broken)

    def test_stripping_touches_only_the_pinned_declaration(self):
        text = "volatile int other;\n" + DECLARATION.replace("; ", ";\n  ") + "\nvolatile u8 *io;\n"
        stripped = semantics.strip_pinned_volatile(text, DECLARATION)
        self.assertEqual(len(stripped), len(text))
        self.assertTrue(stripped.startswith("volatile int other;"))
        self.assertTrue(stripped.endswith("volatile u8 *io;\n"))
        self.assertEqual(stripped.count("volatile"), 2)
        for broken in ("", text + text, text.replace("unknown_3C", "unknown_3E")):
            with self.subTest(text=broken), self.assertRaises(semantics.SemanticError):
                semantics.strip_pinned_volatile(broken, DECLARATION)

    def test_dead_load_before_each_byte_store_is_accepted(self):
        real = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "ldrb\tr0, [r1]", "mov\tr0, #19",
                        "strb\tr0, [r1]", "bx\tlr")
        stripped = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "mov\tr0, #19", "strb\tr0, [r1]",
                            "bx\tlr")
        (result,) = compare(real, stripped)
        self.assertEqual(result, ("func_08028C34", 1, [2], [], [], []))
        self.assertIn("read-modify-write loads at [3]",
                      semantics.record(SYMBOL, [result]))

    def test_register_allocation_and_address_arithmetic_may_differ(self):
        real = assembly("ldr\tr3, .L3", "add\tr2, r3, #0", "add\tr2, r2, #61", "ldrb\tr0, [r2]",
                        "mov\tr1, #0", "strb\tr1, [r2]", "sub\tr2, r2, #1", "ldrb\tr0, [r2]",
                        "strb\tr1, [r2]", "bx\tlr")
        stripped = assembly("ldr\tr2, .L3", "add\tr0, r2, #0", "add\tr0, r0, #61", "mov\tr1, #0",
                            "strb\tr1, [r0]", "add\tr0, r2, #0", "add\tr0, r0, #60",
                            "strb\tr1, [r0]", "bx\tlr")
        self.assertEqual(compare(real, stripped)[0][1:4], (1, [3, 7], []))

    def test_chained_assignment_re_read_is_accepted(self):
        # `sym.unknown_3C = (sym.unknown_3D = 0);`: volatile re-reads 0x3D
        real = assembly("ldr\tr3, .L3", "add\tr2, r3, #0", "add\tr2, r2, #61", "ldrb\tr0, [r2]",
                        "mov\tr1, #0", "strb\tr1, [r2]", "ldrb\tr0, [r2]", "sub\tr2, r2, #1",
                        "ldrb\tr1, [r2]", "strb\tr0, [r2]", "bx\tlr")
        stripped = assembly("ldr\tr3, .L3", "add\tr2, r3, #61", "mov\tr1, #0", "strb\tr1, [r2]",
                            "sub\tr2, r2, #1", "strb\tr1, [r2]", "bx\tlr")
        self.assertEqual(compare(real, stripped)[0][1:4], (1, [3, 8], [6]))
        # the re-read value may only reach pinned byte stores, unchanged:
        # `sym.unknown_3C = (sym.unknown_3D = 0) + 1;` keeps a read the
        # stripped compile does not need
        used = real.replace("ldrb\tr0, [r2]\n\tsub\tr2, r2, #1",
                            "ldrb\tr0, [r2]\n\tadd\tr0, r0, #1\n\tsub\tr2, r2, #1")
        self.assertNotEqual(used, real)
        plus_one = stripped.replace("sub\tr2, r2, #1\n\tstrb\tr1, [r2]",
                                    "sub\tr2, r2, #1\n\tmov\tr1, #1\n\tstrb\tr1, [r2]")
        self.assertNotEqual(plus_one, stripped)
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(used, plus_one)
        self.assertIn("the qualifier added a read", str(caught.exception))

    def test_extra_load_without_its_store_is_refused(self):
        stripped = assembly("ldr\tr1, .L3", "add\tr1, r1, #61", "mov\tr0, #1", "strb\tr0, [r1]",
                            "bx\tlr")
        for name, real in (
                ("bare read", assembly("ldr\tr1, .L3", "add\tr2, r1, #60", "ldrb\tr2, [r2]",
                                       "add\tr1, r1, #61", "ldrb\tr0, [r1]", "mov\tr0, #1",
                                       "strb\tr0, [r1]", "bx\tlr")),
                ("second load before the store", assembly(
                    "ldr\tr1, .L3", "add\tr1, r1, #61", "ldrb\tr2, [r1]", "ldrb\tr0, [r1]",
                    "mov\tr0, #1", "strb\tr0, [r1]", "bx\tlr")),
                ("load of another byte", assembly(
                    "ldr\tr1, .L3", "add\tr1, r1, #61", "ldrb\tr0, [r1, #0]", "sub\tr2, r1, #1",
                    "ldrb\tr2, [r2]", "mov\tr0, #1", "strb\tr0, [r1]", "bx\tlr"))):
            with self.subTest(name=name):
                self.refused(real, stripped, "is a dead load of")

