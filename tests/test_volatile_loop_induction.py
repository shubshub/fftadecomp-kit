    def test_the_content_of_a_pinned_member_may_not_be_live_across_a_loop(self):
        # `t = sym.unknown_3C; <loop>; sym.unknown_3C = t;` is rule 5's self-assignment
        # unrolled; the loop's barrier would hide it, so it is refused at the cut
        read = ("ldr\tr1, .L3", "ldrb\tr5, [r1, #@P@]")
        back = ("ldr\tr1, .L3", ("real", "ldrb\tr2, [r1, #@P@]"), "strb\tr5, [r1, #@P@]")
        self.refused(FRAME + read + loop() + back + END,
                     "the content of a pinned member is live across the loop in r5")
        spilled = FRAME + ("add\tsp, sp, #-8",) + read + ("str\tr5, [sp]",) + loop() + \
            ("ldr\tr5, [sp]",) + back + ("add\tsp, sp, #8",) + END
        self.refused(spilled, "the content of a pinned member is live across the loop in the frame")

    def test_object_content_behind_a_barrier_stays_object_content(self):
        # the check refuses a value read from the object as an address; a loop's
        # barrier may not launder one that memory holds into an ordinary pointer
        address = "is computed from a value read back from memory"
        head = FRAME + ("mov\tr6, r1",)
        # (r3 is cleared again: the calls below may read it, and an object value
        # live across a loop must keep its value)
        read = ("ldr\tr3, .L3", "ldrh\tr3, [r3]", "str\tr3, [r6]", "mov\tr3, #0")

        def second(*use):
            return ("mov\tr5, r2", ".L20:", "ldr\tr7, [r6]") + use + ("sub\tr5, r5, #1", "cmp\tr5, #0",
                                                                    "bhi\t.L20")
        # the dereference behind a test, so that the check without induction meets
        # its bound before it: stored before the loop, read back in it ...
        use = ("ldrb\tr2, [r6, #8]", "cmp\tr2, #0", "beq\t.L19", "ldr\tr7, [r6]", "ldrb\tr0, [r7]", ".L19:")
        self.refused(head + read + loop(*use) + MEMBER + END, address)
        # ... stored by one iteration, read back by the next: the cut is marked and rerun
        self.refused(head + loop(*use, *read) + MEMBER + END, address)
        # stored by one loop, read back by another
        self.refused(head + loop(*read) + second("ldrb\tr0, [r7]") + MEMBER + END, address)
        # stored before one loop, read back in the next: the second barrier hides what the first hid
        self.refused(head + read + loop() + second("ldrb\tr0, [r7]") + MEMBER + END, address)
        # the reruns are bounded: with none allowed, the mark the body needs refuses
        with mock.patch.object(induction, "MAX_RERUNS", 0):
            self.refused(head + loop(*use, *read) + MEMBER + END,
                         "marking the loop barriers that hide object content took more than 0 reruns")
        # read back as an ordinary value, it passes
        self.compare(head + loop(*read) + second("mov\tr0, r7", "bl\tfunc_0802A2C0") + MEMBER + END)
        self.compare(head + loop("ldr\tr7, [r6]", "mov\tr0, r7", "bl\tfunc_0802A2C0", *read) + MEMBER + END)
        # a call between store and loop is the check's own barrier, as without a loop
        self.compare(head + read + ("mov\tr5, r0", "mov\tr0, #0", "bl\tfunc_0802A2C0") +
                     loop("ldr\tr7, [r6]", "ldrb\tr0, [r7]", start="r5") + MEMBER + END)

    def test_pinned_content_may_not_hide_behind_a_barrier(self):
        # rule 5 sees `t = sym.unknown_3C; ...; sym.unknown_3C = t` only through memory
        # the barrier would hide
        pinned = ("ldr\tr1, .L3", "ldrb\tr3, [r1, #@P@]", "str\tr3, [r6]")
        back = ("ldr\tr3, [r6]", "ldr\tr1, .L3", ("real", "ldrb\tr2, [r1, #@P@]"), "strb\tr3, [r1, #@P@]")
        self.refused(FRAME + ("mov\tr6, r1",) + pinned + loop() + back + END,
                     "the content of a pinned member is in memory the loop's barrier would hide")
        self.refused(FRAME + ("mov\tr6, r1",) + loop(*pinned) + back + END,
                     "the loop leaves the content of a pinned member in memory its barrier would hide")

    def test_the_frame_may_not_escape_past_a_barrier_hiding_object_content(self):
        # once the frame escapes, a frame load stops at the barrier, which would hide sp+0
        head = FRAME + ("mov\tr6, r1", "add\tsp, sp, #-8", "ldr\tr1, .L3", "ldrh\tr3, [r1]", "str\tr3, [sp]")
        tail = ("ldr\tr7, [sp]", "ldrb\tr0, [r7]") + MEMBER + ("add\tsp, sp, #8",) + END
        self.refused(head + loop() + ("mov\tr0, sp", "str\tr0, [r6]") + tail,
                     "the frame escapes after a loop whose barrier hides a frame store of a value read from")
        # escaping through a call, the call is the barrier, as without a loop
        self.compare(head + loop() + ("mov\tr0, sp", "bl\tfunc_0802A2C0") + tail)

