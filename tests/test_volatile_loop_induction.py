    def test_object_loads_are_counted_between_loop_cuts(self):
        # each path runs the code after a cut once per iteration, so a load may not move
        # across a cut: equal counts per path are not equal counts per execution
        before = "the stripped compile loads g_control_flags_03000940+0x3c where the real one does not"
        added = "which the stripped compile does not load there; the qualifier added a read"
        read = ("ldr\tr1, .L3", "ldrb\tr2, [r1, #@P@]")
        once = tuple(("stripped", line) for line in read)
        # read every iteration in the real compile (copied, the copy dies), once before the loop
        # in the stripped one
        body = FRAME + ("mov\tr6, r1",) + once + (("stripped", "mov\tr3, r2"),) + \
            loop(*(("real", line) for line in read), ("real", "mov\tr3, r2"), "str\tr4, [r6]") + MEMBER + END
        self.refused(body, before)
        # the same with a compare whose flags die as the use
