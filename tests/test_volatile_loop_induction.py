def assembly(*body, name="func_08028C34"):
    """agbcc-shaped output for one Thumb function with the object in pool .L3"""
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{name}\n\t.type\t {name},function\n\t.thumb_func\n{name}:\n" +
            "".join(f"\t{line}\n" if not line.endswith(":") else f"{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n"
            f"\t.size\t {name},.Lfe1-{name}\n")


def variant(body, which):
    """one compile: ("real", line) is only in the real and permuted ones, ("stripped", line)
    only in the stripped one, ("perturbed", line) only in the permuted one and
    ("unpermuted", line) in the other two; @P@ is unknown_3C's offset, which the
    permutation moves"""
    lines = []
    for line in body:
        if isinstance(line, tuple):
            if line[0] != which and not (line[0] == "real" and which == "perturbed") and \
                    not (line[0] == "unpermuted" and which != "perturbed"):
                continue
            line = line[1]
        lines.append(line.replace("@P@", "61" if which == "perturbed" else "60")
                     .replace("@Q@", "60" if which == "perturbed" else "61"))
    return assembly(*lines)


def compiles(body):
    return tuple(variant(body, which) for which in ("real", "stripped", "perturbed"))


FRAME = ("push\t{r4, r5, r6, r7, lr}",)
END = ("pop\t{r4, r5, r6, r7}", "pop\t{r0}", "bx\tr0")
MEMBER = ("ldr\tr1, .L3", "add\tr1, r1, #@P@", ("real", "ldrb\tr2, [r1]"), "mov\tr2, #1", "strb\tr2, [r1]")


def loop(*body, counter="r4", start="r0"):
    """`do body while (--i)` from an argument: the exit depends on it, and the check's
    depth-first exploration follows the back edge first, so it meets the bound first"""
    return (f"mov\t{counter}, {start}", ".L10:", *body, f"sub\t{counter}, {counter}, #1",
            f"cmp\t{counter}, #0", "bhi\t.L10")


def top_tested(*body):
    """`for (i = arg; i != 0; i--) body`: the exit leaves before the body"""
    return ("mov\tr4, r0", ".L10:", "cmp\tr4, #0", "beq\t.L11", *body, "sub\tr4, r4, #1", "b\t.L10", ".L11:")


class Base(unittest.TestCase):
    def compare(self, body, interfaces=None, preprocessed=PREPROCESSED):
        real, stripped, perturbed = compiles(body)
        return semantics.compare(real, stripped, preprocessed, SYMBOL, DECLARATION, perturbed, interfaces)

    def bounded(self, body, interfaces=None):
        """the check without induction stops at its bound"""
        real, stripped, perturbed = compiles(body)
        with self.assertRaises(semantics.BoundExceeded):
            semantics._compare_compiles(real, stripped, PREPROCESSED, SYMBOL, DECLARATION, perturbed,
                                        interfaces)

    def refused(self, body, reason, interfaces=None):
        self.bounded(body, interfaces)
        with self.assertRaises(semantics.SemanticError) as caught:
            self.compare(body, interfaces)
        message = str(caught.exception)
        self.assertIn("(loops with unknown exit conditions are not modelled); relational loop induction", message)
        self.assertIn("relational loop induction (kit#137): ", message)
        self.assertIn(reason, message.split("relational loop induction (kit#137): ", 1)[1])
        return message

    def interfaces(self):
        return semantics.RomInterfaces(*synthetic_rom())


class InductionTests(Base):
    def test_a_loop_with_an_unknown_count_is_proved_for_every_iteration(self):
        body = FRAME + loop() + MEMBER + END
        self.bounded(body)
        (result,) = self.compare(body)
        self.assertEqual(result[:4], ("func_08028C34", 2, [7], []))
        text = semantics.record(SYMBOL, [result], perturbed=True)
        self.assertEqual(text.split("; ", 1)[1],
                         "`func_08028C34` agrees on 2 paths; read-modify-write loads at [8], chained re-reads at "
                         f"[], loops by relational induction at instructions [3] ({induction.NAME}, premise: "
                         f"{induction.PREMISE})")
        self.assertEqual(text, semantics.record(SYMBOL, self.compare(body), perturbed=True))

    def test_member_stores_inside_the_loop(self):
        (result,) = self.compare(FRAME + loop(*MEMBER) + END)
        self.assertEqual(result[2], [4])

    def test_a_data_dependent_exit(self):
        # `while (*p) p++; sym.unknown_3C = 1;`
        body = FRAME + ("mov\tr5, r0", ".L10:", "ldrb\tr0, [r5]", "cmp\tr0, #0", "beq\t.L11",
                        "add\tr5, r5, #1", "b\t.L10", ".L11:") + MEMBER + END
        self.bounded(body)
        self.assertEqual(self.compare(body)[0][2], [9])

    def test_a_rotated_loop_is_cut_at_its_condition(self):
        body = FRAME + ("mov\tr4, r0", "b\t.L12", ".L10:", "sub\tr4, r4, #1", ".L12:", "cmp\tr4, #0",
                        "bne\t.L10") + MEMBER + END
        (result,) = self.compare(body)
        self.assertEqual(result[-1], (5,))

    def test_nested_and_sequential_loops(self):
        inner = ("mov\tr5, r4", ".L20:", "cmp\tr5, #0", "beq\t.L21", "sub\tr5, r5, #1", "b\t.L20", ".L21:")
        after = ("mov\tr6, r0", ".L30:", "cmp\tr6, #0", "beq\t.L31", "sub\tr6, r6, #1", "b\t.L30", ".L31:")
        (result,) = self.compare(FRAME + loop(*inner) + after + MEMBER + END)
        self.assertEqual(result[-1], (3, 4, 12))

    def test_a_nest_is_proved_loop_by_loop(self):
        # the inner loop's body differs between the compiles on every outer iteration
        inner = ("mov\tr5, r4", ".L20:", "cmp\tr5, #0", "beq\t.L21", ("real", "str\tr5, [r6]"),
                 ("stripped", "str\tr4, [r6]"), "sub\tr5, r5, #1", "b\t.L20", ".L21:")
        self.refused(FRAME + ("mov\tr6, r1",) + loop(*inner) + MEMBER + END, "differ in observable behaviour")
        # the inner loop breaks the outer relation: r7, live at the outer head, takes an address
        inner = ("mov\tr5, r4", ".L20:", "cmp\tr5, #0", "beq\t.L21", "mov\tr7, sp", "sub\tr5, r5, #1", "b\t.L20",
                 ".L21:")
        self.refused(FRAME + ("mov\tr7, r1",) + loop("str\tr4, [r7]", *inner) + MEMBER + END,
                     "r7 holds an address, an object value or a poisoned value at the back edge")

    def test_a_call_inside_the_loop_under_its_rom_interface(self):
        body = FRAME + loop("mov\tr0, r4", "bl\tfunc_08000240") + MEMBER + END
