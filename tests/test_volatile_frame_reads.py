def interleaved(text, old, new):
    """replace old by new in an agbcc -g compile, keeping the .L labels it puts between the lines"""
    import re
    if text.count(old) == 1:
        return text.replace(old, new)
    lines = old.split("\n")[:-1] if old.endswith("\n") else old.split("\n")
    found = list(re.finditer(r"\n(?:(?:\.L\w+:)?\n)*".join(re.escape(line) for line in lines) +
                             ("\n" if old.endswith("\n") else ""), text))
    assert len(found) == 1, (old, len(found))
    labels = "".join(line + "\n" for line in re.findall(r"^\.L\w+:$", found[0].group(0), re.M))
    return text[:found[0].start()] + labels + new + text[found[0].end():]


