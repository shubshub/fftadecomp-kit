    @staticmethod
    def composition_proofs():
        """the composition test's overwrite pair inside a frame, with and without an indexed store
        before the epilogue's pops: the composition proofs, premised and not"""
        import overwritten_control_store_composition as composition
        from test_volatile_semantics import assembly as plain, DECLARATION as declaration, SYMBOL as symbol
        prologue = ("push {r4, lr}", "add sp, sp, #-16")
        indexed = ("lsl r3, r5, #2", "add r3, sp", "str r6, [r3, #8]")
        epilogue = ("add sp, sp, #16", "pop {r4}", "pop {r1}", "bx r1")
        overwrite = ("ldr r2, .L3", "ldrb r0, [r2, #60]", "mov r0, #0", "strb r0, [r2, #60]",
                     "ldrb r0, [r2, #60]", "mov r0, #19", "strb r0, [r2, #60]")
        final = ("ldr r2, .L3", "mov r0, #19", "strb r0, [r2, #60]")
        size, pinned = semantics.pinned_members(declaration)
        _, mapping, _ = semantics.perturbed_declaration(declaration)

        def composed(*middle):
            real, stripped = (plain(*prologue, *middle, *body, *epilogue) for body in (overwrite, final))
            functions = [semantics.parse_assembly(text)[0][NAME]
                         for text in (real, stripped, real.replace("#60", "#61"))]
            return composition.compare_function(NAME, *functions, {NAME: (False, ())}, symbol, size, pinned,
                                                mapping, selector=composition.SELECTOR, premise=composition.PREMISE)

        return composition, symbol, composed(*indexed), composed()

    def test_the_classified_store_composition_record_names_the_premises(self):
        # no frame-read event and no escape, but the epilogue's pops pass an indexed store: the
        # composition admits it on the premises, so its record states them as the plain record does
        composition, symbol, premised, unpremised = self.composition_proofs()
        clause = "; frame reads under premises: " + "; ".join(semantics.FRAME_READ_PREMISES)
        self.assertTrue(composition.record(symbol, [(NAME, premised)]).endswith(clause))
        self.assertNotIn("frame reads under premises", composition.record(symbol, [(NAME, unpremised)]))

    def test_the_composition_record_covers_every_function_of_the_unit(self):
        # match.py writes one composition record over every function of the translation unit: a
        # premised verdict in any of them names the premises, once, and the clause follows the
        # SHA-256 of the results without entering it
        import hashlib
        import json
        composition, symbol, premised, unpremised = self.composition_proofs()
        clause = "; frame reads under premises: " + "; ".join(semantics.FRAME_READ_PREMISES)
        for first, second in ((premised, unpremised), (unpremised, premised), (premised, premised),
                              (unpremised, unpremised)):
            with self.subTest(first=first is premised, second=second is premised):
                results = [("func_08028C34", first), ("func_08028C80", second)]
                digest = hashlib.sha256(json.dumps(results, sort_keys=True,
                                                   separators=(",", ":")).encode()).hexdigest()
                text = composition.record(symbol, results)
                stated = clause if premised is first or premised is second else ""
                self.assertTrue(text.endswith(f"composition SHA-256 {digest}{stated}"))
                self.assertEqual(text.count("frame reads under premises"), 1 if stated else 0)

