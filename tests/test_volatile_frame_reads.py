def verdict(run):
    """"accept", with the premises the record names, or the refusal message"""
    try:
        results = run()
    except semantics.SemanticError as refusal:
        return str(refusal)
    return "accept" + (" with premises" if results[0][-1] == list(semantics.FRAME_READ_PREMISES) else "")


