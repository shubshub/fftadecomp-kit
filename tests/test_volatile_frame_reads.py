class ExtentsRetry:
    """kit#373 composed with this rule: match.py re-runs a refused check once with escaped-local
    extents (escaped_local_extents.retry).  These classes run the tests above with compare()
    doing that retry, for a hand layout of named locals (LAYOUT "whole": one local over the
    body frame; "words": a 4-byte local at each frame word), and the retry, like
    escaped_local_extents.retry, keeps main's refusal whenever it fails.  So every verdict of
    this module stands under the retry."""
    LAYOUT = None

    def setUp(self):
        patcher = unittest.mock.patch.dict(globals(), {"compare": self.retried})
        patcher.start()
        self.addCleanup(patcher.stop)

    def retried(self, real, stripped_):
        import escaped_local_extents as extents
        try:
            return _main_compare(real, stripped_)
        except semantics.SemanticError as refusal:
            try:
                models = {}
                for label, body in (("real", real), ("stripped", stripped_)):
                    parsed = semantics.parse_assembly(assembly(*body))[0][NAME]
                    _, size = extents.frame_shape(parsed)
                    layout = [extents.Local("a", 0, size, ())] if self.LAYOUT == "whole" and size else \
                        [extents.Local(f"w{k}", 4 * k, 4, ()) for k in range(size // 4)] \
                        if self.LAYOUT == "words" else []
                    models[(label, NAME)] = extents.FrameModel(NAME, label, layout, parsed)
                token = semantics.FRAME_MODELS.set(models)
                try:
                    return _main_compare(real, stripped_)
                finally:
                    semantics.FRAME_MODELS.reset(token)
            except Exception:
                raise refusal from None


