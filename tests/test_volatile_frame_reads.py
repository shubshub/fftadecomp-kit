    def test_escape_events_carry_the_stores_only_when_they_need_to(self):
        trace, = traces(*PROLOGUE + slot(1) + ESCAPE + EPILOGUE)
        self.assertEqual(trace[0], ("escape", ((0, 1), (1, 0), (2, 0), (3, 0))))
        trace, = traces(*PROLOGUE + slot(1) + ("str\tr1, [r2]",) + ESCAPE + EPILOGUE)
        self.assertEqual(kinds(trace), ["store", "escape", "call", "return"])
        self.assertEqual(len(trace[1]), 2)
        trace, = traces(*PROLOGUE + slot(1) + INDEXED_STORE + ESCAPE + ESCAPE + EPILOGUE)
        self.assertEqual(kinds(trace), ["store", "escape", "call", "escape", "call", "return"])
        self.assertEqual(trace[1][2], (("bytes", ((0, 1), (1, 0), (2, 0), (3, 0))),
                                       ("store", trace[0][2], 4, ("entry", "r6"))))
        self.assertEqual(len(trace[3]), 2)
        # only frame stores join, across a call and a store through a pointer argument
        for tail in (ESCAPE, INDEX + ("ldr\tr0, [r3, #8]",)):
            trace, = traces(*PROLOGUE + CALL + slot(1) + ("str\tr1, [r2]",) + INDEXED_STORE + tail + EPILOGUE)
            self.assertEqual(kinds(trace)[:4], ["call", "store", "store", "escape" if tail == ESCAPE else "frame-read"])
