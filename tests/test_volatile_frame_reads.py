import sys
import unittest
import unittest.mock
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import volatile_semantics as semantics


SYMBOL = "g_control_flags_03000940"
DECLARATION = ("extern struct { u16 display; u8 unknown_02[0x3A]; volatile u8 unknown_3C : 8; "
               "volatile u8 unknown_3D : 8; } " + SYMBOL + ";")
PREPROCESSED = ("int func_08028C34(int, int, int);\nextern void func_0802A2C0(int);\n"
                "extern void func_0802A2D0(int *);\n")
NAME = "func_08028C34"


def assembly(*body):
    """agbcc-shaped output for one Thumb function with a one-word pool"""
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{NAME}\n\t.type\t {NAME},function\n\t.thumb_func\n{NAME}:\n" +
            "".join(f"\t{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n\t.size\t {NAME},.Lfe1-{NAME}\n")


def compare(real, stripped):
    return semantics._compare_compiles(assembly(*real), assembly(*stripped), PREPROCESSED, SYMBOL,
                                       DECLARATION)


def traces(*body):
    """the trace of every path of one compile"""
    functions, _ = semantics.parse_assembly(assembly(*body))
    scope = semantics.file_scope(semantics.translation_unit(PREPROCESSED))
    names = {NAME} | {operands[0] for mnemonic, operands, _ in functions[NAME][0] if mnemonic == "bl"}
    signatures = {name: semantics.function_signature(scope, name) for name in names}
    size, pinned = semantics.pinned_members(DECLARATION)
    return [path.trace for path in semantics.explore(NAME, functions[NAME], signatures, "real",
                                                     (SYMBOL, size, pinned))]


def kinds(trace):
    return [event[0] for event in trace]


PROLOGUE = ("push\t{r4, lr}", "add\tsp, sp, #-16")
EPILOGUE = ("add\tsp, sp, #16", "pop\t{r4}", "pop\t{r1}", "bx\tr1")
INDEX = ("lsl\tr3, r5, #2", "add\tr3, sp")                 # r3 = sp + 4*r5: a[r5] at sp+8
CALL = ("mov\tr0, #0", "bl\tfunc_0802A2C0")
PASS = ("mov\tr1, #0", "mov\tr2, #0", "mov\tr3, #0", "bl\tfunc_0802A2C0")
ESCAPE = ("mov\tr0, sp", "add\tr0, #8", "bl\tfunc_0802A2D0")


def slot(value):
    """sp+8 = value"""
    return (f"mov\tr1, #{value}", "str\tr1, [sp, #8]")


INDEXED_STORE = INDEX + ("str\tr6, [r3, #8]",)             # a[r5] = r6


def array_return(value):
    """`int a[2]; a[0] = value; a[1] = 0; return a[i & 1];` (the issue's leaf, i in r0)"""
    return ("push\t{lr}", "add\tsp, sp, #-8", f"mov\tr1, #{value}", "str\tr1, [sp]", "mov\tr1, #0",
            "str\tr1, [sp, #4]", "mov\tr1, #1", "and\tr0, r1", "lsl\tr0, r0, #2", "mov\tr1, sp",
            "add\tr1, r1, r0", "ldr\tr0, [r1]", "add\tsp, sp, #8", "pop\t{r1}", "bx\tr1")


def indexed_read(value, call=True):
    """sp+8 = value, (a call), then a[r5] passed to a call (the issue's case with a call)"""
    return PROLOGUE + slot(value) + (CALL if call else ()) + INDEX + ("ldr\tr0, [r3, #8]",) + PASS + EPILOGUE


# agbcc -O2 output of the issue's C (`a[0] = v; a[1] = v + 1; flag = 1; return a[i & 1];`)
RET_REAL = ("add\tsp, sp, #-8", "str\tr1, [sp]", "add\tr1, r1, #1", "str\tr1, [sp, #4]", "ldr\tr1, .L3",
            "add\tr1, r1, #60", "ldrb\tr2, [r1]", "mov\tr2, #1", "strb\tr2, [r1]", "and\tr0, r0, r2",
            "lsl\tr0, r0, #2", "add\tr0, r0, sp", "ldr\tr0, [r0]", "add\tsp, sp, #8", "bx\tlr")
# `int a[4]; a[1] = v; a[i & 3] = 5; flag = 1; return a[1];`
RELOAD_REAL = ("add\tsp, sp, #-16", "str\tr1, [sp, #4]", "mov\tr1, #3", "and\tr1, r1, r0",
               "lsl\tr1, r1, #2", "add\tr1, r1, sp", "mov\tr0, #5", "str\tr0, [r1]", "ldr\tr0, .L3",
               "add\tr0, r0, #60", "ldrb\tr1, [r0]", "mov\tr1, #1", "strb\tr1, [r0]", "ldr\tr0, [sp, #4]",
               "add\tsp, sp, #16", "bx\tlr")
# `int a[4]; a[0] = v; a[i & 3] = 5; flag = 1; func_0802A2D0(a);`
ESCAPE_REAL = ("push\t{lr}", "add\tsp, sp, #-16", "str\tr1, [sp]", "mov\tr1, #3", "and\tr1, r1, r0",
               "lsl\tr1, r1, #2", "add\tr1, r1, sp", "mov\tr0, #5", "str\tr0, [r1]", "ldr\tr0, .L3",
               "add\tr0, r0, #60", "ldrb\tr1, [r0]", "mov\tr1, #1", "strb\tr1, [r0]", "mov\tr0, sp",
               "bl\tfunc_0802A2D0", "add\tsp, sp, #16", "pop\t{r0}", "bx\tr0")

UNION_REAL = ("add\tsp, sp, #-4", "str\tr1, [sp]", "mov\tr1, #3", "and\tr1, r1, r0", "mov\tr2, sp",
              "add\tr1, r1, sp", "mov\tr0, #7", "strb\tr0, [r1]", "ldr\tr0, .L3", "add\tr0, r0, #60",
              "ldrb\tr1, [r0]", "mov\tr1, #1", "strb\tr1, [r0]", "ldrb\tr0, [r2, #1]", "add\tsp, sp, #4",
              "bx\tlr")


def stripped(real):
    """agbcc's stripped compile of the same source: the dead `ldrb` is gone"""
    return tuple(line for line in real if not line.startswith("ldrb"))


def swapped(body, constant):
    """move the constant store `constant` after the indexed store that follows it, as r2 code"""
    body = list(body)
    at = body.index(constant)
    indexed = body[at + 1:at + 7]
    renamed = [line.replace("r1", "r2") for line in indexed]
    return tuple(body[:at] + renamed + [constant] + body[at + 7:])


class FrameReadTests(unittest.TestCase):
    def refused(self, real, stripped_, reason):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real, stripped_)
        self.assertIn(reason, str(caught.exception))
        return str(caught.exception)

    def test_indexed_read_without_a_call_binds_the_local_stores(self):
        message = self.refused(array_return(1), array_return(2), "differ in observable behaviour")
        self.assertIn("event 1: real frame read32 (and(arg(0x0), 0x1)*0x4 + sp + 0xfffffff4) after "
                      "[{-0xc: 0x1, -0xb: 0x0, -0xa: 0x0, -0x9: 0x0, -0x8: 0x0, -0x7: 0x0, -0x6: 0x0, "
                      "-0x5: 0x0}], stripped frame read32 (and(arg(0x0), 0x1)*0x4 + sp + 0xfffffff4) after "
                      "[{-0xc: 0x2, -0xb: 0x0, -0xa: 0x0, -0x9: 0x0, -0x8: 0x0, -0x7: 0x0, -0x6: 0x0, "
                      "-0x5: 0x0}]", message)
        compare(array_return(1), array_return(1))

    def test_indexed_read_after_a_call_binds_the_local_stores(self):
        self.refused(indexed_read(1), indexed_read(2), "event 2: real frame read32")
        self.refused(indexed_read(1, call=False), indexed_read(2, call=False), "event 1: real frame read32")
        compare(indexed_read(1), indexed_read(1))

    def test_fixed_read_across_an_indexed_store_in_either_order(self):
        tail = ("ldr\tr0, [sp, #8]",) + PASS + EPILOGUE
        one_first = PROLOGUE + slot(1) + INDEXED_STORE + tail
        indexed_first = PROLOGUE + INDEXED_STORE + slot(1) + tail
        self.refused(one_first, indexed_first, "differ in observable behaviour")
        self.refused(indexed_first, one_first, "differ in observable behaviour")
        compare(one_first, one_first)
        compare(indexed_first, indexed_first)

    def test_fixed_read_across_an_indexed_store_binds_the_stores_before_it(self):
        def body(value):
            return PROLOGUE + slot(value) + INDEXED_STORE + ("ldr\tr0, [sp, #8]",) + PASS + EPILOGUE
        self.refused(body(1), body(2), "event 2: real frame read32 (sp + 0xfffffff0) after "
                     "[{-0x10: 0x1, -0xf: 0x0, -0xe: 0x0, -0xd: 0x0}, store32 (entry(r5)*0x4 + sp + 0xfffffff0)")
        compare(body(1), body(1))

    def test_escape_after_an_indexed_store_binds_their_order(self):
        one_first = PROLOGUE + slot(1) + INDEXED_STORE + ESCAPE + EPILOGUE
        indexed_first = PROLOGUE + INDEXED_STORE + slot(1) + ESCAPE + EPILOGUE
        message = self.refused(one_first, indexed_first, "differ in observable behaviour")
        self.assertIn("real frame escape {+0x0: 0x1, +0x1: 0x0, +0x2: 0x0, +0x3: 0x0} after "
                      "[{+0x0: 0x1, +0x1: 0x0, +0x2: 0x0, +0x3: 0x0}, store32 (entry(r5)*0x4 + sp + 0xfffffff0) "
                      "<- entry(r6)]", message)
        compare(one_first, one_first)

    def test_a_byte_of_a_union_behind_an_indexed_byte_store(self):
        # `union { int w; u8 b[4]; } u; u.w = v; u.b[i & 3] = 7; flag = 1; return u.b[1];` (agbcc -O2):
        # main refused the read as a partial overlap of u.w; it is a frame read now
        union_stripped = tuple(line for line in UNION_REAL if line != "ldrb\tr1, [r0]")
        compare(UNION_REAL, union_stripped)
        for old, new in (("str\tr1, [sp]", "strh\tr1, [sp]"), ("mov\tr0, #7", "mov\tr0, #8"),
                         ("ldrb\tr0, [r2, #1]", "ldrb\tr0, [r2, #2]"), ("mov\tr1, #3", "mov\tr1, #1")):
            with self.subTest(edit=new):
                self.refused(UNION_REAL, tuple(new if line == old else line for line in union_stripped),
                             "differ in observable behaviour")

    def test_genuine_agbcc_pairs_pass_and_edited_ones_do_not(self):
        compare(RET_REAL, stripped(RET_REAL))
        edited = tuple(line.replace("add\tr1, r1, #1", "add\tr1, r1, #2") for line in stripped(RET_REAL))
        self.refused(RET_REAL, edited, "differ in observable behaviour")
        compare(RELOAD_REAL, stripped(RELOAD_REAL))
        self.refused(RELOAD_REAL, swapped(stripped(RELOAD_REAL), "str\tr1, [sp, #4]"),
                     "differ in observable behaviour")
        compare(ESCAPE_REAL, stripped(ESCAPE_REAL))
        self.refused(ESCAPE_REAL, swapped(stripped(ESCAPE_REAL), "str\tr1, [sp]"),
                     "differ in observable behaviour")

    def test_the_read_is_the_version_of_its_value(self):
        trace, = traces(*array_return(1))
        self.assertEqual(kinds(trace), ["frame-read", "return"])
        value = trace[1][1]
        self.assertEqual(value[0], "load")
        self.assertEqual(value[3], ("frame-read", 0))
        self.assertEqual(value[2], trace[0][1])
        trace, = traces(*PROLOGUE + slot(1) + INDEX + ("ldrb\tr0, [r3, #8]",) + EPILOGUE)
        self.assertEqual(semantics.show_event(trace[0]), "frame read8 (entry(r5)*0x4 + sp + 0xfffffff0) "
                         "after [{-0x10: 0x1, -0xf: 0x0, -0xe: 0x0, -0xd: 0x0}]")
        self.assertEqual(trace[1], ("return", ("load", 1, trace[0][1], ("frame-read", 0))))

    def test_the_record_names_the_premises_a_verdict_relies_on(self):
        premises = ("frame reads under premises: no callee holds a frame address before the frame escapes; "
                    "a variable offset from sp reaches no pushed callee-saved register or lr")
        # a frame read, an escape carrying the stores, a fixed read across an indexed store, and pops
        # (saved slots) passing an indexed store before or after an escape
        for body in (array_return(1), PROLOGUE + slot(1) + INDEXED_STORE + ESCAPE + EPILOGUE,
                     PROLOGUE + slot(1) + INDEXED_STORE + ("ldr\tr0, [sp, #8]",) + PASS + EPILOGUE,
                     PROLOGUE + INDEXED_STORE + slot(1) + ("ldr\tr0, [sp, #8]",) + EPILOGUE,
                     PROLOGUE + ESCAPE + INDEXED_STORE + EPILOGUE,
                     # a leaf whose only reliance is the first escape (through a store) carrying the stores
                     ("add\tsp, sp, #-16",) + INDEX + ("str\tr6, [r3, #8]", "mov\tr2, sp", "str\tr2, [r1]",
                                                       "add\tsp, sp, #16", "bx\tlr")):
            with self.subTest(body=body):
                results = compare(body, body)
                self.assertEqual(results[0][-1], list(semantics.FRAME_READ_PREMISES))
                self.assertTrue(semantics.record(SYMBOL, results, perturbed=True).endswith(
                    "chained re-reads at [], " + premises))
        # a verdict that relies on neither keeps its result and record, an indexed store included
        for body in (PROLOGUE + slot(1) + ESCAPE + EPILOGUE, PROLOGUE + slot(1) + ("ldr\tr0, [sp, #8]",) + EPILOGUE,
                     PROLOGUE + slot(1) + ("str\tr1, [r2]",) + EPILOGUE,
                     ("add\tsp, sp, #-8",) + INDEX + ("str\tr1, [r3]", "add\tsp, sp, #8", "bx\tlr"),
                     # a leaf whose frame escapes through a store; a[i + 1] is read past a[i]
                     ("add\tsp, sp, #-16", "mov\tr2, sp", "str\tr2, [r1]") + INDEX +
                     ("str\tr6, [r3, #8]", "ldr\tr0, [r3, #12]", "add\tsp, sp, #16", "bx\tlr"),
                     # a loaded value stored over a saved slot past an indexed store: the store's
                     # self-assignment probe relies on nothing
                     ("push\t{r4}", "add\tsp, sp, #-8") + INDEX + ("str\tr6, [r3]", "ldr\tr2, [r0]",
                                                                   "str\tr2, [sp, #8]", "add\tsp, sp, #12", "bx\tlr")):
            with self.subTest(body=body):
                results = compare(body, body)
                self.assertEqual(results, [(NAME, 1, [], [], [], [])])
                self.assertEqual(semantics.record(SYMBOL, results),
                                 f"* allowlisted volatile semantics: `{SYMBOL}` stripped of volatile compiles to "
                                 f"the same behaviour; `{NAME}` agrees on 1 path; read-modify-write loads at [], "
                                 "chained re-reads at []")
        # the stripped compile's reliance counts too: a leaf against a compile whose pop of lr passes
        # the same indexed store
        indexed = ("lsl\tr3, r5, #2", "add\tr3, sp", "str\tr6, [r3]", "mov\tr0, #0")
        leaf = ("add\tsp, sp, #-16",) + indexed + ("add\tsp, sp, #16", "bx\tlr")
        framed = ("push\t{lr}", "add\tsp, sp, #-12") + indexed + ("add\tsp, sp, #12", "pop\t{r1}", "bx\tr1")
        self.assertEqual(compare(leaf, leaf), [(NAME, 1, [], [], [], [])])
        self.assertEqual(compare(leaf, framed)[0][-1], list(semantics.FRAME_READ_PREMISES))
        self.assertEqual(compare(framed, leaf)[0][-1], list(semantics.FRAME_READ_PREMISES))

