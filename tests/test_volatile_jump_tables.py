"""kit#170: agbcc's guarded jump-table dispatch in the volatile semantic check."""

import sys
import unittest
from pathlib import Path
from unittest import mock

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import volatile_semantics as semantics


SYMBOL = "g_control_flags_03000940"
DECLARATION = ("extern struct { u16 display; u8 unknown_02[0x3A]; volatile u8 unknown_3C : 8; "
               "volatile u8 unknown_3D : 8; } " + SYMBOL + ";")
PREPROCESSED = "void func_08028C34(int);\n"

GUARD = ("cmp\tr0, #2", "bhi\t.L20")
DISPATCH = ("lsl\tr0, r0, #2", "ldr\tr2, .L12", "add\tr0, r0, r2", "ldr\tr0, [r0]", "mov\tpc, r0")
POOL = (".L13:", ".align\t2, 0", ".L12:", ".word\t.L11", ".align\t2, 0", ".L11:")
TABLE = (".word\t.L5", ".word\t.L6", ".word\t.L5")
# `switch (x) { case 0: case 2: sym.unknown_3C = 1; break; case 1: sym.unknown_3D = 2; }`
CASES = (".L5:", "add\tr1, r1, #60", "ldrb\tr2, [r1]", "mov\tr2, #1", "strb\tr2, [r1]", "b\t.L20",
         ".L6:", "add\tr1, r1, #61", "ldrb\tr2, [r1]", "mov\tr2, #2", "strb\tr2, [r1]",
         ".L20:", "bx\tlr")


def assembly(guard=GUARD, dispatch=DISPATCH, pool=POOL, table=TABLE, cases=CASES, name="func_08028C34"):
    """agbcc-shaped output: a jump-table switch and a one-word symbol pool"""
    body = ("ldr\tr1, .L3",) + tuple(guard) + tuple(dispatch) + tuple(pool) + tuple(table) + tuple(cases)
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{name}\n\t.type\t {name},function\n\t.thumb_func\n{name}:\n" +
            "".join(f"{line}\n" if line.endswith(":") else f"\t{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n"
            f"\t.size\t {name},.Lfe1-{name}\n")


def stripped(text):
    return text.replace("ldrb\tr2, [r1]\n\t", "")


def moved(text):
    return text.replace("#60", "#6X").replace("#61", "#60").replace("#6X", "#61")


def compare(real, other=None, perturbed=None):
    return semantics.compare(real, stripped(real) if other is None else other, PREPROCESSED,
                             SYMBOL, DECLARATION, moved(real) if perturbed is None else perturbed)


class JumpTableTests(unittest.TestCase):
    def refused(self, reason, real, other=None, perturbed=None):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real, other, perturbed)
        self.assertIn(reason, str(caught.exception))

    def test_guarded_dispatch_is_a_branch_to_each_distinct_case(self):
        # the default and the two distinct labels; the shared label is one path
        (result,) = compare(assembly())
        self.assertEqual(result[:4], ("func_08028C34", 3, [9, 14], []))
        # agbcc's far guard `bls .LCB; b .Ldefault @long jump`
        far = assembly(guard=("cmp\tr0, #2", "bls\t.LCB9", "b\t.L20", ".LCB9:"))
        self.assertEqual(compare(far)[0][1], 3)
        # the stripped compile may number its labels and pick registers otherwise
        renamed = stripped(assembly()).replace(".L5", ".L7").replace(".L11", ".L15").replace(
            ".L12", ".L16").replace("r2, .L16", "r3, .L16").replace("r0, r0, r2", "r0, r0, r3")
        self.assertEqual(compare(assembly(), renamed)[0][1], 3)
        # `lsl rD, rI, #2` with the table pointer in the index register
        other = assembly(dispatch=("lsl\tr3, r0, #2", "ldr\tr0, .L12", "add\tr3, r3, r0",
                                   "ldr\tr3, [r3]", "mov\tpc, r3"))
        self.assertEqual(compare(other)[0][1], 3)
        # a known constant index needs no guard and takes its own case only
        constant = assembly(guard=("mov\tr0, #1",))
        self.assertEqual(compare(constant)[0][1], 1)

    def test_each_case_is_checked_against_the_stripped_compile(self):
        # a store without its read-modify-write load in one case only
        unloaded = CASES[:8] + CASES[9:]
        self.refused("without the read-modify-write load", assembly(cases=unloaded),
                     stripped(assembly(cases=unloaded)))
        # the cases still follow the permuted members
        self.refused("does not follow its member", assembly(), perturbed=assembly())

    def test_an_unguarded_or_misguarded_index_is_refused(self):
        reason = "not bounded by `cmp r0, #2`"
        self.refused(reason, assembly(guard=()))
        self.refused(reason, assembly(guard=("cmp\tr3, #2", "bhi\t.L20")))
        self.refused(reason, assembly(guard=("cmp\tr0, #3", "bhi\t.L20")))
        self.refused(reason, assembly(guard=("cmp\tr0, #2", "bcs\t.L20")))
        # the guard's other side, and an index changed after its guard
        self.refused(reason, assembly(guard=("cmp\tr0, #2", "bls\t.L20")))
        self.refused(reason, assembly(guard=GUARD + ("add\tr0, r0, #1",)))
        self.refused("lies beyond", assembly(guard=("mov\tr0, #3",)))

    def test_a_constant_read_back_from_memory_is_no_known_index(self):
        # `x = 1` through a byte of memory: the reload is derived, so the
        # dispatch needs its guard, and the case is a recorded decision
        spilled = ("mov\tr0, #1", "strb\tr0, [sp]", "ldrb\tr0, [sp]")
        self.refused("not bounded by `cmp r0, #2`", assembly(guard=spilled))
        guarded = assembly(guard=spilled + GUARD)
        self.assertEqual(compare(guarded)[0][1], 3)
        function = semantics.parse_assembly(guarded)[0]["func_08028C34"]
        paths = semantics.explore("func_08028C34", function, {}, "real", (SYMBOL, 0x3E, {0x3C: 1, 0x3D: 1}))
        self.assertEqual(sorted(c[0] for p in paths for c in p.conditions if c[0] == "jump-table"),
                         ["jump-table", "jump-table"])
        self.assertTrue(all(c[1] == 1 and c[2] == 2 and c[3] == (0, 1, 0)
                            for p in paths for c in p.conditions if c[0] == "jump-table"))

    def test_the_table_must_be_the_adjacent_local_one_with_one_entry_per_index(self):
        self.refused("not bounded by `cmp r0, #3`", assembly(table=TABLE + (".word\t.L6",)))
        self.refused("not bounded by `cmp r0, #1`", assembly(table=TABLE[:2]))
        # the table, or its pointer, elsewhere
        self.refused("does not immediately follow", assembly(
            pool=POOL[:-1], table=(), cases=CASES + (".align\t2, 0", ".L11:") + TABLE))
        self.refused("pointer is not a local label word", assembly(
            pool=(".L13:", ".align\t2, 0", ".L11:"),
            cases=CASES + (".L14:", ".align\t2, 0", ".L12:", ".word\t.L11")))
        self.refused("pointer is not a local label word", assembly(
            pool=(".L13:", ".align\t2, 0", ".L12:", ".word\t.L11+4", ".align\t2, 0", ".L11:")))
        self.refused("pointer is not a local label word", assembly(
            pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".align\t2, 0", ".L11:")))
        # entries: another function, an unknown or offset label, a data label
        for entry in ("func_08028C34", ".L99", ".L6+2", ".L12", ".L3", "0x08000000"):
            with self.subTest(entry=entry):
                self.refused("not a local code label", assembly(table=TABLE[:2] + (f".word\t{entry}",)))

    def test_the_pointer_may_share_the_pool_dumped_at_the_jump(self):
        # agbcc dumps the literals still pending at `mov pc` into one pool
        # there, so the table pointer can be any word of it (`.L42+40`)
        shared = assembly(dispatch=DISPATCH[:1] + ("ldr\tr2, .L12+4",) + DISPATCH[2:],
                          pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11",
                                ".align\t2, 0", ".L11:"))
        self.assertEqual(compare(shared)[0][1], 3)
        first = assembly(pool=(".L13:", ".align\t2, 0", ".L12:", ".word\t.L11", f".word\t{SYMBOL}",
                               ".align\t2, 0", ".L11:"))
        self.assertEqual(compare(first)[0][1], 3)
        # the stripped compile may hold the pointer at another offset
        self.assertEqual(compare(shared, stripped(assembly()))[0][1], 3)
        self.assertEqual(compare(assembly(), stripped(shared))[0][1], 3)
        # a table that follows its pool with no alignment in between
        self.assertEqual(compare(assembly(
            dispatch=DISPATCH[:1] + ("ldr\tr2, .L12+4",) + DISPATCH[2:],
            pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11", ".L11:")))[0][1], 3)

    def test_a_shared_pointer_word_must_be_exactly_the_adjacent_table_label(self):
        pool = (".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11", ".align\t2, 0", ".L11:")
        def via(operand, pool=pool, cases=CASES):
            return assembly(dispatch=DISPATCH[:1] + (f"ldr\tr2, {operand}",) + DISPATCH[2:], pool=pool,
                            cases=cases)
        reason = "pointer is not a local label word"
        # the other word of the pool, a misaligned or out-of-pool offset
        for operand in (".L12", ".L12+2", ".L12+6", ".L12+8", ".L12+12"):
            with self.subTest(operand=operand):
                self.refused(reason, via(operand))
        # a misaligned offset whose word index is the pointer's
        self.refused(reason, assembly(dispatch=DISPATCH[:1] + ("ldr\tr2, .L12+2",) + DISPATCH[2:]))
        # an offset label word, or a pool that is not the one at the jump
        self.refused(reason, via(".L12+4", pool=pool[:4] + (".word\t.L11+4",) + pool[5:]))
        self.refused(reason, via(".L12+4", pool=(".L13:", ".align\t2, 0", ".L11:"),
                                 cases=CASES + (".L14:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}",
                                                ".word\t.L11")))
        # an offset that runs from the pool into the table reads a case label,
        # which is no table
        self.refused("does not immediately follow", via(
            ".L12+8", pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11", ".L11:")))

    def test_a_shared_pointer_dispatches_through_the_table_it_names(self):
        # the pointer may name either of two tables at the jump; the model
        # reads the one the `ldr` loads, and a compile that names another
        # is a different program
        dispatch = DISPATCH[:1] + ("ldr\tr2, .L12+4",) + DISPATCH[2:]
        def decoy(*entries):
            return assembly(dispatch=dispatch, pool=(
                ".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L31", ".align\t2, 0",
                ".L31:") +
                tuple(f".word\t{entry}" for entry in entries) + (".align\t2, 0", ".L11:"))
        # one shared label: the default and that label, not the adjacent table's three paths
        self.assertEqual(compare(decoy(".L5", ".L5", ".L5"))[0][1], 2)
        # the same partition with the cases swapped, and another partition
        swapped, merged = decoy(".L6", ".L5", ".L6"), decoy(".L5", ".L5", ".L6")
        self.assertEqual(compare(swapped)[0][1], 3)
        self.refused("differ in observable behaviour", swapped, stripped(assembly()), moved(swapped))
        self.refused("a jump table where the explored compile branches otherwise", merged,
                     stripped(assembly()), moved(merged))
        # a shared pointer to a table that is not at the jump
        self.refused("does not immediately follow", assembly(
            dispatch=dispatch,
            pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11", ".align\t2, 0",
                  ".L14:"),
            table=(), cases=CASES + (".align\t2, 0", ".L11:") + TABLE))

    def test_a_leading_zero_offset_is_refused(self):
        # GAS reads `.L12+020` as octal 16: word 4, the table .L31, where a
        # decimal reading takes word 5, the table .L11
        octal = assembly(dispatch=DISPATCH[:1] + ("ldr\tr2, .L12+020",) + DISPATCH[2:], pool=(
            ".L13:", ".align\t2, 0", ".L12:") + (f".word\t{SYMBOL}",) * 4 + (
            ".word\t.L31", ".word\t.L11", ".align\t2, 0", ".L31:", ".word\t.L6", ".word\t.L5", ".word\t.L6",
            ".align\t2, 0", ".L11:"))
        self.refused("unsupported memory operand `.L12+020`", octal)
        # the ordinary literal load reads its offset the same way
        literal = assembly().replace("ldr\tr1, .L3\n", "ldr\tr1, .L3+00\n")
        self.refused("unsupported memory operand `.L3+00`", literal)
        self.assertEqual(compare(literal.replace(".L3+00", ".L3+0"))[0][1], 3)

    def test_any_other_computed_jump_fails_closed(self):
        reason = "computed jumps are not modelled"
        for index, change in ((4, "mov\tpc, r2"), (4, "bx\tr0"), (3, "ldr\tr0, [r0, #4]"),
                              (2, "add\tr0, r2, r0"), (0, "lsl\tr0, r0, #3"), (1, "mov\tr2, r3")):
            with self.subTest(change=change):
                dispatch = DISPATCH[:index] + (change,) + DISPATCH[index + 1:]
                self.refused(reason, assembly(dispatch=dispatch))
        # a pointer below its pool label is no dispatch (and no literal load)
        self.refused("unsupported memory operand `.L12-4`", assembly(
            dispatch=DISPATCH[:1] + ("ldr\tr2, .L12-4",) + DISPATCH[2:],
            pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11", ".align\t2, 0",
                  ".L11:")))
        # the table pointer loaded over the scaled index: `add r0, r0, r0`
        # doubles the pointer and is no dispatch
        self.refused(reason, assembly(dispatch=DISPATCH[:1] + ("ldr\tr0, .L12", "add\tr0, r0, r0") +
                                      DISPATCH[3:]))
        # entering the dispatch past its shift
        self.refused(reason, assembly(guard=GUARD + ("b\t.L30",),
                                      dispatch=DISPATCH[:1] + (".L30:",) + DISPATCH[1:]))

    def test_both_compiles_must_dispatch_alike(self):
        branches = assembly(guard=GUARD + ("cmp\tr0, #1", "beq\t.L6", "b\t.L5"), dispatch=(), pool=(),
                            table=())
        self.refused("a conditional branch where the explored compile dispatches", assembly(),
                     stripped(branches))
        self.refused("a jump table where the explored compile branches", branches,
                     stripped(assembly()), moved(branches))
        # the same labels shared differently is a different program
        other = stripped(assembly(table=(".word\t.L5", ".word\t.L6", ".word\t.L6")))
        self.refused("branch on different conditions", assembly(), other)

    def test_cases_count_toward_the_path_bound(self):
        with mock.patch.object(semantics, "MAX_PATHS", 2):
            self.refused("has more than 2 paths; the semantic check is bounded", assembly())
        with mock.patch.object(semantics, "MAX_PATHS", 3):
            self.assertEqual(compare(assembly())[0][1], 3)


class DataLabelTargetTests(unittest.TestCase):
    """kit#368: a label is where the model resumes only when an instruction
    follows it directly, and a table is read as written only on a word boundary"""

    NAME = "func_08028C34"
    SHARED = DISPATCH[:1] + ("ldr\tr2, .L12+4",) + DISPATCH[2:]
    # an `.align` between the default label and its instruction: any padding
    # there runs as `lsl r0, r0, #0`, which the instruction stream does not hold
    PADDED = CASES[:-1] + (".align\t2, 0", "bx\tlr")

    def refused(self, reason, real):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real)
        self.assertIn(reason, str(caught.exception))

    def test_the_parser_tells_code_labels_and_aligned_words_apart(self):
        import json
        labels = semantics.parse_assembly(assembly())[0][self.NAME][1]
        # the barriers .L13 and .L4, the pools and the table precede data
        self.assertEqual(labels.code, {".L5", ".L6", ".L20"})
        self.assertEqual(labels.aligned, {".L12", ".L11", ".L3"})
        # the map other tools read and pin is the plain one it was
        self.assertEqual(dict(labels), {".L13": 8, ".L12": 8, ".L11": 8, ".L5": 8, ".L6": 13, ".L20": 17,
                                        ".L4": 18, ".L3": 18, ".Lfe1": 18})
        self.assertEqual(json.dumps(labels, sort_keys=True), json.dumps(dict(labels), sort_keys=True))
        labels = semantics.parse_assembly(assembly(cases=self.PADDED))[0][self.NAME][1]
        self.assertEqual(labels.code, {".L5", ".L6"})
        # a table label inside an aligned run is aligned; one after a bare
        # label, or after an instruction that follows an aligned pool, is not
        run = assembly(dispatch=self.SHARED, pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}",
                                                   ".word\t.L11", ".L11:"))
        self.assertLessEqual({".L12", ".L11"}, semantics.parse_assembly(run)[0][self.NAME][1].aligned)
        bare = assembly(pool=(".L13:", ".L11:"), table=TABLE + (".align\t2, 0", ".L12:", ".word\t.L11"))
        self.assertEqual(semantics.parse_assembly(bare)[0][self.NAME][1].aligned, {".L12", ".L3"})

    def test_a_branch_to_a_label_that_data_follows_is_refused(self):
        # the model would resume at .L5, past the words the hardware runs
        for label in (".L11", ".L12", ".L13"):
            with self.subTest(label=label):
                self.refused(f"branch to `{label}`, a label that no instruction follows directly",
                             assembly(guard=("cmp\tr0, #2", f"bhi\t{label}")))
        self.refused("branch to `.L20`, a label that no instruction follows directly",
                     assembly(cases=self.PADDED))
        # a table between the default label and its instruction (the fixture
        # two tests above used for a table that is not at the jump)
        self.refused("branch to `.L20`, a label that no instruction follows directly", assembly(
            pool=POOL[:-1], table=(), cases=CASES[:-1] + (".align\t2, 0", ".L11:") + TABLE + ("bx\tlr",)))
        # an unconditional branch resolves its label the same way
        self.refused("branch to `.L13`, a label that no instruction follows directly",
                     assembly(guard=("b\t.L13",)))
        # the first case label follows the table directly and is code
        self.assertEqual(compare(assembly(guard=("cmp\tr0, #2", "bhi\t.L5")))[0][1], 3)
        self.assertEqual(compare(assembly(guard=("b\t.L5",)))[0][1], 1)

    def test_a_table_entry_must_be_a_label_an_instruction_follows(self):
        reason = "a jump-table entry is not a local code label of this function"
        # .L13 is the barrier before the pool's alignment: the hardware would
        # jump into the pool, where the model resumes at .L5
        self.refused(reason, assembly(table=TABLE[:2] + (".word\t.L13",)))
        # a label with alignment between it and the instruction it indexes
        self.refused(reason, assembly(table=TABLE[:2] + (".word\t.L21",),
                                      cases=CASES[:-2] + (".L21:", ".align\t2, 0") + CASES[-2:]))
        # the barrier and the pool at the end, which index no instruction
        for entry in (".L4", ".L3"):
            with self.subTest(entry=entry):
                self.refused(reason, assembly(table=TABLE[:2] + (f".word\t{entry}",)))
        # the label after the table, and the last label of the function, are code
        self.assertEqual(compare(assembly(table=TABLE[:2] + (".word\t.L20",)))[0][1], 4)
        self.assertEqual(compare(assembly(table=(".word\t.L5",) * 3))[0][1], 2)

    def test_a_table_not_known_to_be_word_aligned_is_refused(self):
        reason = "the jump table is not known to start on a word boundary"
        after = (".align\t2, 0", ".L12:", ".word\t.L11")
        # nine instructions, then the table at 0x12 with its pointer after it:
        # `ldr r0, [r0]` there loads rotated halves of two entries
        nine = ("add\tr3, r3, #0",) + GUARD
        self.refused(reason, assembly(guard=nine, pool=(".L13:", ".L11:"), table=TABLE + after))
        # at 0x10 by count only: nothing in the text says so
        self.refused(reason, assembly(pool=(".L13:", ".L11:"), table=TABLE + after))
        # only agbcc's own `.align 2, 0` is read as an alignment: not one to
        # two bytes, one with no fill value, one that `.pool` follows, or one
        # with a limit on the bytes it may skip
        for before in ((".align\t1, 0",), (".align\t2",), (".align\t2, 0", ".pool"), (".align\t2, 0, 1",)):
            with self.subTest(before=before):
                self.refused(reason, assembly(pool=(".L13:",) + before + (".L11:",), table=TABLE + after))
        # `.align 2, 0, 1` skips at most one byte, so after nine instructions
        # the table stays at 0x12
        self.refused(reason, assembly(guard=nine, pool=(".L13:", ".align\t2, 0, 1", ".L11:"), table=TABLE + after))
        # a table that continues a literal run no `.align 2, 0` started is not
        # aligned: here the run starts at 0x12 and the table at 0x16
        self.refused(reason, assembly(guard=nine, pool=(".L13:", ".L40:", ".word\t0", ".L11:"),
                                      table=TABLE + after))
        # an aligned pool earlier in the function does not carry over the
        # instructions after it
        early = ("b\t.L50", ".L51:", ".align\t2, 0", ".L52:", ".word\t0", ".L50:")
        self.refused(reason, assembly(guard=early + GUARD, pool=(".L13:", ".L11:"), table=TABLE + after))
        # the same table after its own alignment, and one that continues the
        # aligned run of its pointer with no alignment between
        self.assertEqual(compare(assembly(guard=early + GUARD))[0][1], 3)
        self.assertEqual(compare(assembly(pool=(".L13:", ".align\t2, 0", ".L11:"), table=TABLE + after))[0][1], 3)
        self.assertEqual(compare(assembly(dispatch=self.SHARED, pool=(
            ".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".word\t.L11", ".L11:")))[0][1], 3)


