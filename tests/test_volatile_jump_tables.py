"""kit#170: agbcc's guarded jump-table dispatch in the volatile semantic check."""

import sys
import unittest
from pathlib import Path
from unittest import mock

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
import volatile_semantics as semantics


SYMBOL = "g_control_flags_03000940"
DECLARATION = ("extern struct { u16 display; u8 unknown_02[0x3A]; volatile u8 unknown_3C : 8; "
               "volatile u8 unknown_3D : 8; } " + SYMBOL + ";")
PREPROCESSED = "void func_08028C34(int);\n"

GUARD = ("cmp\tr0, #2", "bhi\t.L20")
DISPATCH = ("lsl\tr0, r0, #2", "ldr\tr2, .L12", "add\tr0, r0, r2", "ldr\tr0, [r0]", "mov\tpc, r0")
POOL = (".L13:", ".align\t2, 0", ".L12:", ".word\t.L11", ".align\t2, 0", ".L11:")
TABLE = (".word\t.L5", ".word\t.L6", ".word\t.L5")
# `switch (x) { case 0: case 2: sym.unknown_3C = 1; break; case 1: sym.unknown_3D = 2; }`
CASES = (".L5:", "add\tr1, r1, #60", "ldrb\tr2, [r1]", "mov\tr2, #1", "strb\tr2, [r1]", "b\t.L20",
         ".L6:", "add\tr1, r1, #61", "ldrb\tr2, [r1]", "mov\tr2, #2", "strb\tr2, [r1]",
         ".L20:", "bx\tlr")


def assembly(guard=GUARD, dispatch=DISPATCH, pool=POOL, table=TABLE, cases=CASES, name="func_08028C34"):
    """agbcc-shaped output: a jump-table switch and a one-word symbol pool"""
    body = ("ldr\tr1, .L3",) + tuple(guard) + tuple(dispatch) + tuple(pool) + tuple(table) + tuple(cases)
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{name}\n\t.type\t {name},function\n\t.thumb_func\n{name}:\n" +
            "".join(f"{line}\n" if line.endswith(":") else f"\t{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n"
            f"\t.size\t {name},.Lfe1-{name}\n")


def stripped(text):
    return text.replace("ldrb\tr2, [r1]\n\t", "")


def moved(text):
    return text.replace("#60", "#6X").replace("#61", "#60").replace("#6X", "#61")


def compare(real, other=None, perturbed=None):
    return semantics.compare(real, stripped(real) if other is None else other, PREPROCESSED,
                             SYMBOL, DECLARATION, moved(real) if perturbed is None else perturbed)


class JumpTableTests(unittest.TestCase):
    def refused(self, reason, real, other=None, perturbed=None):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real, other, perturbed)
        self.assertIn(reason, str(caught.exception))

    def test_guarded_dispatch_is_a_branch_to_each_distinct_case(self):
        # the default and the two distinct labels; the shared label is one path
        (result,) = compare(assembly())
        self.assertEqual(result[:4], ("func_08028C34", 3, [9, 14], []))
        # agbcc's far guard `bls .LCB; b .Ldefault @long jump`
        far = assembly(guard=("cmp\tr0, #2", "bls\t.LCB9", "b\t.L20", ".LCB9:"))
        self.assertEqual(compare(far)[0][1], 3)
        # the stripped compile may number its labels and pick registers otherwise
        renamed = stripped(assembly()).replace(".L5", ".L7").replace(".L11", ".L15").replace(
            ".L12", ".L16").replace("r2, .L16", "r3, .L16").replace("r0, r0, r2", "r0, r0, r3")
        self.assertEqual(compare(assembly(), renamed)[0][1], 3)
        # `lsl rD, rI, #2` with the table pointer in the index register
        other = assembly(dispatch=("lsl\tr3, r0, #2", "ldr\tr0, .L12", "add\tr3, r3, r0",
                                   "ldr\tr3, [r3]", "mov\tpc, r3"))
        self.assertEqual(compare(other)[0][1], 3)
        # a known constant index needs no guard and takes its own case only
        constant = assembly(guard=("mov\tr0, #1",))
        self.assertEqual(compare(constant)[0][1], 1)

    def test_each_case_is_checked_against_the_stripped_compile(self):
        # a store without its read-modify-write load in one case only
        unloaded = CASES[:8] + CASES[9:]
        self.refused("without the read-modify-write load", assembly(cases=unloaded),
                     stripped(assembly(cases=unloaded)))
        # the cases still follow the permuted members
        self.refused("does not follow its member", assembly(), perturbed=assembly())

    def test_an_unguarded_or_misguarded_index_is_refused(self):
        reason = "not bounded by `cmp r0, #2`"
        self.refused(reason, assembly(guard=()))
        self.refused(reason, assembly(guard=("cmp\tr3, #2", "bhi\t.L20")))
        self.refused(reason, assembly(guard=("cmp\tr0, #3", "bhi\t.L20")))
        self.refused(reason, assembly(guard=("cmp\tr0, #2", "bcs\t.L20")))
        # the guard's other side, and an index changed after its guard
        self.refused(reason, assembly(guard=("cmp\tr0, #2", "bls\t.L20")))
        self.refused(reason, assembly(guard=GUARD + ("add\tr0, r0, #1",)))
        self.refused("lies beyond", assembly(guard=("mov\tr0, #3",)))

    def test_the_table_must_be_the_adjacent_local_one_with_one_entry_per_index(self):
        self.refused("not bounded by `cmp r0, #3`", assembly(table=TABLE + (".word\t.L6",)))
        self.refused("not bounded by `cmp r0, #1`", assembly(table=TABLE[:2]))
        # the table, or its pointer, elsewhere
        self.refused("does not immediately follow", assembly(
            pool=POOL[:-1], table=(), cases=CASES[:-1] + (".align\t2, 0", ".L11:") + TABLE + ("bx\tlr",)))
        self.refused("pointer is not a local label word", assembly(
            pool=(".L13:", ".align\t2, 0", ".L11:"),
            cases=CASES + (".L14:", ".align\t2, 0", ".L12:", ".word\t.L11")))
        self.refused("pointer is not a local label word", assembly(
            pool=(".L13:", ".align\t2, 0", ".L12:", ".word\t.L11+4", ".align\t2, 0", ".L11:")))
        self.refused("pointer is not a local label word", assembly(
            pool=(".L13:", ".align\t2, 0", ".L12:", f".word\t{SYMBOL}", ".align\t2, 0", ".L11:")))
        # entries: another function, an unknown or offset label, a data label
        for entry in ("func_08028C34", ".L99", ".L6+2", ".L12", ".L3", "0x08000000"):
            with self.subTest(entry=entry):
                self.refused("not a local code label", assembly(table=TABLE[:2] + (f".word\t{entry}",)))

    def test_any_other_computed_jump_fails_closed(self):
        reason = "computed jumps are not modelled"
        for index, change in ((4, "mov\tpc, r2"), (4, "bx\tr0"), (3, "ldr\tr0, [r0, #4]"),
                              (2, "add\tr0, r2, r0"), (0, "lsl\tr0, r0, #3"), (1, "mov\tr2, r3")):
            with self.subTest(change=change):
                dispatch = DISPATCH[:index] + (change,) + DISPATCH[index + 1:]
                self.refused(reason, assembly(dispatch=dispatch))
        # entering the dispatch past its shift
        self.refused(reason, assembly(guard=GUARD + ("b\t.L30",),
                                      dispatch=DISPATCH[:1] + (".L30:",) + DISPATCH[1:]))

    def test_both_compiles_must_dispatch_alike(self):
        branches = assembly(guard=GUARD + ("cmp\tr0, #1", "beq\t.L6", "b\t.L5"), dispatch=(), pool=(),
                            table=())
        self.refused("a conditional branch where the explored compile dispatches", assembly(),
                     stripped(branches))
        self.refused("a jump table where the explored compile branches", branches,
                     stripped(assembly()), moved(branches))
        # the same labels shared differently is a different program
        other = stripped(assembly(table=(".word\t.L5", ".word\t.L6", ".word\t.L6")))
        self.refused("branch on different conditions", assembly(), other)

    def test_cases_count_toward_the_path_bound(self):
        with mock.patch.object(semantics, "MAX_PATHS", 2):
            self.refused("has more than 2 paths; the semantic check is bounded", assembly())
        with mock.patch.object(semantics, "MAX_PATHS", 3):
            self.assertEqual(compare(assembly())[0][1], 3)


if __name__ == "__main__":
    unittest.main()
