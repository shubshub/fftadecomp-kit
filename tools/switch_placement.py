"""Closed agbcc assembly grammar and address-derived Thumb entry context."""

import re
import shlex
from contextlib import contextmanager


RULE = "thumb-entry-context-v1"
INSERTION = b"\t.space\t2, 0\n"
MNEMONICS = frozenset((
    "adc", "add", "and", "asr", "b", "beq", "bne", "bcs", "bcc", "bmi", "bpl",
    "bvs", "bvc", "bhi", "bls", "bge", "blt", "bgt", "ble", "bl", "bx", "bic",
    "cmn", "cmp", "eor", "ldmia", "ldr", "ldrb", "ldrh", "ldrsb", "ldrsh",
    "lsl", "lsr", "mov", "mul", "mvn", "neg", "orr", "pop", "push", "ror",
    "sbc", "stmia", "str", "strb", "strh", "sub", "tst", "nop"))


def origin(address):
    if type(address) is not int or address % 2 or not 0x08000000 <= address < 0x09000000:
        raise ValueError("placement requires an even original-ROM address")
    return address - address % 4, address % 4


def place(raw, address):
    _, prefix = origin(address)
    if type(raw) is not bytes or len(raw) > 1024 * 1024 or not raw.endswith(b"\n"):
        raise ValueError("unsupported raw assembly input")
    try:
        text = raw.decode("ascii")
    except UnicodeError as error:
        raise ValueError("assembly must be ASCII") from error
    if any(character not in "\n\t" and not 32 <= ord(character) <= 126 for character in text):
        raise ValueError("unsupported assembly characters")
    lines = text.splitlines(keepends=True)
    name = f"func_{address:08X}"
    envelope = (
        r"@ Generated by gcc 2\.9-arm-000512 for Thumb/elf",
        r"\s*\.code\s+16", r"\.gcc2_compiled\.:", r"\.text",
        r"\s*\.align\s+2, 0", rf"\s*\.globl\s+{name}",
        rf"\s*\.type\s+{name},function", r"\s*\.thumb_func", rf"{name}:")
    if len(lines) <= len(envelope) or any(re.fullmatch(pattern, line.rstrip("\n")) is None
                                         for pattern, line in zip(envelope, lines)):
        raise ValueError("noncanonical compiler entry envelope")
    labels = set()
    finished = False
    for index, line in enumerate(lines[len(envelope):], start=len(envelope)):
        statement = line.strip()
        if not statement:
            continue
        if finished:
            raise ValueError("assembly after sized function")
        label = re.fullmatch(r"(\.L(?:fe|CB)?[0-9]+):", statement)
        if label:
            if label[1] in labels:
                raise ValueError("duplicate compiler local label")
            labels.add(label[1])
        elif re.fullmatch(r"\.align\s+2, 0", statement):
            continue
        elif re.fullmatch(r"\.word\s+(?:-?[0-9]+|0x[0-9a-fA-F]+|\.L[0-9]+(?:\+[0-9]+)?)", statement):
            continue
        elif re.fullmatch(rf"\.size\s+{name},(\.Lfe[0-9]+)-{name}", statement):
            end = re.fullmatch(rf"\.size\s+{name},(\.Lfe[0-9]+)-{name}", statement)[1]
            if end not in labels or lines[index - 1].strip() != end + ":":
                raise ValueError("size must immediately follow the end label")
            finished = True
        else:
            annotated = re.fullmatch(r"(b(?:eq|ne|cs|cc|mi|pl|vs|vc|hi|ls|ge|lt|gt|le)\s+\.L[0-9]+)\s+@cond_branch", statement)
            annotated = annotated or re.fullmatch(r"(b\s+\.L[0-9]+)\s+@long jump", statement)
            if annotated:
                statement = annotated[1]
            instruction = re.fullmatch(r"([a-z]+)(?:\s+([a-zA-Z0-9_., #+!{}\[\]-]+))?", statement)
            if instruction is None or instruction[1] not in MNEMONICS:
                raise ValueError(f"unsupported compiler assembly statement: {statement!r}")
    if not finished:
        raise ValueError("missing canonical function size")
    position = sum(len(line) for line in lines[:7])
    placed = raw if not prefix else raw[:position] + INSERTION + raw[position:]
    return placed, position


@contextmanager
def workspace(runner):
    with runner.workspace() as directory:
        try:
            yield directory
        finally:
            runner.sh(f"rm -f -- {shlex.quote(directory + '/f.raw.s')}")


def compile_object(runner, workspace, args, root, address, source, thumb=True):
    from match import elf_image, verify_dependencies
    if thumb is not True:
        raise ValueError("placement is Thumb-only")
    temporary = shlex.quote(workspace)
    environment = f"export TMPDIR={temporary}; "
    runner.sh(f"{environment}{args.cpp} -nostdinc -undef -I include {shlex.quote(source)} -o {temporary}/f.i")
    verify_dependencies(runner.read_binary(f"{workspace}/f.i").decode("utf-8"), root, address)
    runner.sh(f"{environment}{args.cc} {args.flags} {temporary}/f.i -o {temporary}/f.raw.s")
    raw = runner.read_binary(f"{workspace}/f.raw.s")
    placed, _ = place(raw, address)
    runner.write_text(f"{workspace}/f.s", placed.decode("ascii"))
    runner.sh(f"{environment}{args.assembler} -mthumb-interwork {temporary}/f.s -o {temporary}/f.o")
    runner.sh(f"{args.objcopy} -O binary --only-section=.text {temporary}/f.o {temporary}/f.bin")
    original = runner.read_binary(f"{workspace}/f.o")
    image = elf_image(original)
    if runner.read_binary(f"{workspace}/f.bin") != image["text"] or \
            runner.read_binary(f"{workspace}/f.raw.s") != raw or runner.read_binary(f"{workspace}/f.s") != placed:
        raise ValueError("assembly stage or object capture changed")
    return original, image["text"], image
