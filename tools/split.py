#!/usr/bin/env python3
"""
split.py - turn the analysis into a splat-style decomp tree.

Reads config/coverage.json + config/functions.json (written by analyze.py) and
writes, under asm/ and files/:

  asm/code_<rom addr>.s   one file per 64 KiB of ROM: every discovered function
                          as labelled assembly, every non-code gap as
                          .incbin (inline .byte when the gap is tiny)
  files/code_<a>_<b>.bin  raw bytes of each code run
  files/data_<a>_<b>.bin  raw bytes of each data run
  symbols/ffta.sym        addr / size / name per function
  asm/manifest.json       every run of the ROM in order, so tools/rebuild.py
                          can prove the split is byte-exact

Runs tile the ROM exactly once: concatenating files/*.bin in manifest order
reproduces baserom.bin.
"""

import json
import os
import sys

try:
    from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM, CS_MODE_THUMB
except ImportError:
    sys.exit("split.py needs capstone:  python -m pip install capstone")

ROM_BASE = 0x08000000
CHUNK = 0x10000          # one .s per 64 KiB of ROM
INCBIN_MIN = 8           # gaps smaller than this are emitted as .byte
MIN_CODE_RUN = 16        # shorter "code" runs are noise, fold them into data
CODE_CHUNK_MIN = 0x400   # a 64 KiB window needs this many code bytes to
                         # count as a code chunk (kills gfx false positives)


def rom_path_default(here):
    """the ROM to analyse: the one in this directory, whatever it is called"""
    from rompath import rom_path
    return rom_path(here)


def normalize(cov):
    """merge neighbours and fold implausibly short code runs into data"""
    out = []
    for start, end, kind in cov:
        kind = 0 if (kind and end - start < MIN_CODE_RUN) else kind
        if out and out[-1][2] == kind:
            out[-1][1] = end
        else:
            out.append([start, end, kind])
    # fold away code runs that sit between two data runs and are tiny
    merged = []
    for run in out:
        if (run[2] != 0 and run[1] - run[0] < MIN_CODE_RUN
                and merged and merged[-1][2] == 0):
            merged[-1][1] = run[1]
            continue
        merged.append(run)
    return merged


def repo_root(arg=None):
    """The decomp repo this tool operates on.

    Defaults to the current directory (or $FFTA_ROOT), so the tools can live
    in their own repository - see fftadecomp-kit.
    """
    return os.path.abspath(arg or os.environ.get("FFTA_ROOT") or os.getcwd())


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    here = repo_root(args[1] if len(args) > 1 else None)
    rom_path = args[0] if args else rom_path_default(here)
    rom = open(rom_path, "rb").read()

    cov = json.load(open(os.path.join(here, "config", "coverage.json")))
    funcs = json.load(open(os.path.join(here, "config", "functions.json")))
    cov = normalize(cov)
    funcs_by_start = {int(f["rom"], 16) - ROM_BASE: f for f in funcs}

    for d in ("asm", "files", "symbols"):
        os.makedirs(os.path.join(here, d), exist_ok=True)
    for d in ("asm", "files"):
        for f in os.listdir(os.path.join(here, d)):
            os.remove(os.path.join(here, d, f))

    arm = Cs(CS_ARCH_ARM, CS_MODE_ARM)
    thumb = Cs(CS_ARCH_ARM, CS_MODE_THUMB)

    parts = []          # (kind, path, start, end) - tiles the ROM in order
    asm_files = []
    n_code = n_data = 0
    tail_start = 0
    all_runs = []

    for base in range(0, len(rom), CHUNK):
        end = min(base + CHUNK, len(rom))
        runs = [(max(s, base), min(e, end), k)
                for s, e, k in cov if e > base and s < end]
        runs.sort()
        code_bytes = sum(e - s for s, e, k in runs if k)
        has_code = code_bytes >= CODE_CHUNK_MIN
        if not has_code:
            # too little code here to be a code section: one data file
            runs = [(base, end, 0)]
        lines = []
        if has_code:
            lines = [
                f"@ FFTA - ROM 0x{ROM_BASE+base:08X}-0x{ROM_BASE+end:08X}",
                "@ generated by tools/split.py from baserom.bin - do not hand-edit",
                "    .section .text",
                f"    .org 0x{ROM_BASE+base:08X}",
                "",
            ]

        for start, stop, kind in runs:
            name = ("code_" if kind else "data_") + f"{start:08X}_{stop:08X}.bin"
            rel = f"files/{name}"
            with open(os.path.join(here, "files", name), "wb") as f:
                f.write(rom[start:stop])
            parts.append(("code" if kind else "data", rel, start, stop))
            all_runs.append((start, stop, rel))

            if kind == 0:
                n_data += 1
                if has_code:
                    lines.extend(emit_data(start, stop, rel))
                continue

            n_code += 1
            if has_code:
                lines.extend(emit_code(start, stop, rom, arm, thumb,
                                       funcs_by_start))
        if has_code:
            fname = f"code_{base:08X}.s"
            with open(os.path.join(here, "asm", fname), "w",
                      encoding="utf-8", newline="\n") as f:
                f.write("\n".join(lines) + "\n")
            asm_files.append((fname, base, end))
            tail_start = end

    # everything past the last code chunk, as one includeable file
    tail = [f"@ FFTA - ROM 0x{ROM_BASE+tail_start:08X}-0x{ROM_BASE+len(rom):08X}",
            "@ data / assets / padding after the last code chunk, in file order",
            "    .section .text",
            f"    .org 0x{ROM_BASE+tail_start:08X}",
            ""]
    for s, e, rel in all_runs:
        if s < tail_start:
            continue
        tail.append(f"@ {e - s:,} bytes at 0x{ROM_BASE+s:08X}")
        tail.append(f'    .incbin "../{rel}"')
    with open(os.path.join(here, "asm", "tail.s"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write("\n".join(tail) + "\n")

    with open(os.path.join(here, "symbols", "ffta.sym"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write("# FFTA function symbols: address size name\n")
        for fn in funcs:
            s = int(fn["rom"], 16)
            e = int(fn["end"], 16)
            f.write(f"{fn['rom']} {e - s:06X} func_{fn['rom'][2:]}\n")

    manifest = {
        "rom": os.path.basename(rom_path),
        "parts": [{"kind": k, "path": p, "start": f"0x{ROM_BASE+s:08X}",
                   "end": f"0x{ROM_BASE+e:08X}"} for k, p, s, e in parts],
        "asm": [{"file": f"asm/{n}", "start": f"0x{ROM_BASE+s:08X}",
                 "end": f"0x{ROM_BASE+e:08X}"} for n, s, e in asm_files],
        "code_runs": n_code,
        "data_runs": n_data,
        "functions": len(funcs),
    }
    with open(os.path.join(here, "asm", "manifest.json"), "w",
              encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=1)

    print(f"split: {len(asm_files)} asm chunks, {n_code} code runs, "
          f"{n_data} data runs, {len(funcs)} functions")
    print("wrote asm/, files/, symbols/ffta.sym")


def emit_data(start, end, rel):
    size = end - start
    if size < INCBIN_MIN:
        return ([f"@ data 0x{ROM_BASE+start:08X} ({size} bytes)"]
                + [f'    .incbin "../{rel}"'])
    return [f"@ data 0x{ROM_BASE+start:08X} ({size} bytes)",
            f'    .incbin "../{rel}"']


def emit_code(start, end, rom, arm, thumb, funcs_by_start):
    """disassemble a covered run; label every discovered function"""
    out = []
    inside = sorted(f for f in funcs_by_start if start <= f < end)
    pos = start
    for fstart in inside:
        if fstart < pos:                       # overlaps a function already out
            continue
        if fstart > pos:
            out.append(f"@ unclaimed bytes 0x{ROM_BASE+pos:08X}"
                       f"-0x{ROM_BASE+fstart:08X} (see files/code_*.bin)")
            out.append(f'    .incbin "../files/code_{pos:08X}_{fstart:08X}.bin"')
        fn = funcs_by_start[fstart]
        fstop = min(max(int(fn["end"], 16) - ROM_BASE, fstart + 2), end)
        is_thumb = fn["mode"] == "thumb"
        cs = thumb if is_thumb else arm
        out.append("")
        out.append(f"@ {'Thumb' if is_thumb else 'ARM'} function {fn['rom']}"
                   f"  ({fn['instrs']} instrs, found via {fn['kind']})")
        out.append(f"    .{'thumb' if is_thumb else 'arm'}")
        out.append(f"    .global func_{fn['rom'][2:]}")
        out.append(f"func_{fn['rom'][2:]}:")
        used = 0
        for ins in cs.disasm(rom[fstart:fstop], ROM_BASE + fstart):
            out.append(f"    {ins.mnemonic} {ins.op_str}".rstrip())
            used += ins.size
        if used < fstop - fstart:
            out.append(f"@ {fstop - fstart - used} bytes the disassembler "
                       f"would not take (literal pool / tail data)")
            out.append(f'    .incbin "../files/code_'
                       f'{fstart + used:08X}_{fstop:08X}.bin"')
        pos = fstop
    if pos < end:
        out.append(f"@ unclaimed bytes 0x{ROM_BASE+pos:08X}-0x{ROM_BASE+end:08X}")
        out.append(f'    .incbin "../files/code_{pos:08X}_{end:08X}.bin"')
    return out


if __name__ == "__main__":
    main()